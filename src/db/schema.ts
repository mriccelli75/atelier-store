import { relations, sql } from "drizzle-orm";
import {
  boolean,
  check,
  index,
  integer,
  jsonb,
  pgEnum,
  pgTable,
  text,
  timestamp,
  unique,
  uuid,
} from "drizzle-orm/pg-core";

export type ProductImage = { src: string; alt: string };

/** A size option. `available: false` means that size is sold out. */
export type ProductSize = { label: string; available: boolean };

/** Which shop section a product belongs to. Unisex products appear in every section. */
export const departmentEnum = pgEnum("department", ["women", "men", "unisex"]);
export type Department = (typeof departmentEnum.enumValues)[number];

const timestamps = {
  createdAt: timestamp("created_at", { withTimezone: true })
    .notNull()
    .defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true })
    .notNull()
    .defaultNow()
    .$onUpdate(() => new Date()),
};

export const categories = pgTable("categories", {
  id: integer("id").primaryKey().generatedAlwaysAsIdentity(),
  slug: text("slug").notNull().unique(),
  name: text("name").notNull(),
  sortOrder: integer("sort_order").notNull().default(0),
  /** Tile image for "Shop by category" on the homepage. */
  imageSrc: text("image_src"),
  imageAlt: text("image_alt"),
  ...timestamps,
});

export const products = pgTable(
  "products",
  {
    id: integer("id").primaryKey().generatedAlwaysAsIdentity(),
    slug: text("slug").notNull().unique(),
    categoryId: integer("category_id")
      .notNull()
      .references(() => categories.id, { onDelete: "restrict" }),
    department: departmentEnum("department").notNull().default("unisex"),
    name: text("name").notNull(),
    material: text("material").notNull(),
    description: text("description").notNull(),
    details: text("details").array().notNull().default(sql`'{}'::text[]`),
    care: text("care").notNull(),
    priceCents: integer("price_cents").notNull(),
    stockQuantity: integer("stock_quantity").notNull().default(0),
    /** First image is the listing image; the rest are gallery views. */
    images: jsonb("images").$type<ProductImage[]>().notNull(),
    /** Null for items that don't come in sizes. */
    sizes: jsonb("sizes").$type<ProductSize[]>(),
    isNew: boolean("is_new").notNull().default(false),
    ...timestamps,
  },
  (t) => [
    index("products_category_id_idx").on(t.categoryId),
    index("products_department_idx").on(t.department),
    check("products_price_cents_check", sql`${t.priceCents} >= 0`),
    check("products_stock_quantity_check", sql`${t.stockQuantity} >= 0`),
  ],
);

export const categoriesRelations = relations(categories, ({ many }) => ({
  products: many(products),
}));

export const productsRelations = relations(products, ({ one }) => ({
  category: one(categories, {
    fields: [products.categoryId],
    references: [categories.id],
  }),
}));

